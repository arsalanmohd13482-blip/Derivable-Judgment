"""## 4. ANOVA Test
Perform a one-way Analysis of Variance (ANOVA) test to determine if numerical metrics (like cholesterol_level or glucose_level) significantly differ across multiple independent age_groups.
"""

# first import test from the library.
from scipy.stats import f_oneway

# Define the age group.
df["age_group"] = pd.cut(
    df["age"],
    bins=[0, 30, 50, 100],
    labels=["Young", "Middle-aged", "Older"]
)
# The Hypothesis.
# H0 = There is no significan difference between the mean of  all three age group vs cholestrol_level or Glucode level(μ1​=μ2​=μ3).
# H1 = At least one group mean is different

young = df.loc[df["age_group"] == "Young", "cholesterol_level"].dropna()
middle = df.loc[df["age_group"] == "Middle-aged", "cholesterol_level"].dropna()
older = df.loc[df["age_group"] == "Older", "cholesterol_level"].dropna()

f_stat, p_value = f_oneway(young, middle, older)

print("F-statistic:", f_stat)
print("P-value:", p_value)

alpha = 0.05
if p_value >= alpha:
  print("Fail to Reject H0: There is no significant difference between these three Age Groups.")
else :
  print('Accept the Alternate Hypothesis there is difference between these category.')

