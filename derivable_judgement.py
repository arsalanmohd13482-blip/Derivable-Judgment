"""## 3. Confidence Intervals
Calculate the confidence intervals (e.g., 95%) for key numerical data like `age`, `weight`, and `bmi` to estimate the population parameters.


"""

import scipy.stats as stats
import numpy as np
# Confidence Interval for the numeric column like age, weight and bmi.
# so we make one function to calculate the confidence interval.

def Confidence_interval(data, confidence = 0.95):
  n = len(data)
  mean = np.mean(data)
  std = np.std(data)

  standard_error = std / np.sqrt(n)

  critical_value = stats.t.ppf(
        (1 + confidence) / 2,
        df=n-1
    )

  margin_of_error = critical_value * standard_error

  lower = mean - margin_of_error
  upper = mean + margin_of_error

  return mean, lower, upper

# Now calultate for the age, bmi  and weight.
ci_age = tuple(Confidence_interval(df['age']))
ci_bmi = tuple(Confidence_interval(df['bmi']))
ci_weight = tuple(Confidence_interval(df['weight']))


